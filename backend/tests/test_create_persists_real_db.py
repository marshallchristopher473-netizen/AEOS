def _as_json(row):
    """Shape a row the way PostgREST serializes it to the supabase-py client."""
    shaped = {}
    for key, value in row.items():
        if isinstance(value, uuid.UUID):
            value = str(value)
        elif isinstance(value, (datetime.datetime, datetime.date)):
            value = value.isoformat()
        elif isinstance(value, decimal.Decimal):
            value = float(value)
        shaped[key] = value
    return shaped


class _Query:
    def __init__(self, client, table):
        self.client = client
        self.table = table
        self.columns = "*"
        self.filters = []
        self.row_limit = None
        self.payload = None

    def select(self, columns="*", **_kwargs):
        self.columns = columns
        return self

    def eq(self, column, value):
        self.filters.append((column, value))
        return self

    def limit(self, value):
        self.row_limit = value
        return self

    def insert(self, payload):
        self.payload = dict(payload)
        return self

    def execute(self):
        if self.payload is not None:
            return SimpleNamespace(data=[self.client.insert(self.table, self.payload)])
        return SimpleNamespace(
            data=self.client.select(self.table, self.columns, self.filters, self.row_limit)
        )


class RealDbClient:
    """Service-role stand-in for the supabase-py client, backed by PostgreSQL."""

    def __init__(self, conn):
        self.conn = conn
        # Application-supplied ids that were dropped before insert, per table.
        self.discarded_ids = {}

    def table(self, name):
        return _Query(self, name)

    def insert(self, table, payload):
        supplied = payload.pop("id", None)
        if supplied is not None:
            self.discarded_ids.setdefault(table, []).append(str(supplied))
        columns = list(payload)
        values = [Jsonb(v) if isinstance(v, (dict, list)) else v for v in payload.values()]
        statement = sql.SQL("INSERT INTO public.{} ({}) VALUES ({}) RETURNING *").format(
            sql.Identifier(table),
            sql.SQL(", ").join(map(sql.Identifier, columns)),
            sql.SQL(", ").join([sql.Placeholder()] * len(columns)),
        )
        return _as_json(self.conn.execute(statement, values).fetchone())

    def select(self, table, columns, filters, row_limit):
        if columns.strip() == "*":
            selected = sql.SQL("*")
        else:
            selected = sql.SQL(", ").join(
                sql.Identifier(column.strip()) for column in columns.split(",")
            )
        where = sql.SQL(" AND ").join(
            sql.SQL("{} = %s").format(sql.Identifier(column)) for column, _ in filters
        ) if filters else sql.SQL("TRUE")
        statement = sql.SQL("SELECT {} FROM public.{} WHERE {}").format(
            selected, sql.Identifier(table), where
        )
        if row_limit is not None:
            statement += sql.SQL(" LIMIT {}").format(sql.Literal(row_limit))
        rows = self.conn.execute(statement, [value for _, value in filters]).fetchall()
        return [_as_json(row) for row in rows]


@pytest.fixture(scope="module")
def fresh_database():
    """Shim + the full migration chain + the synthetic tenants, in a scratch
    database of its own so the rows these tests commit cannot disturb the
    session database the RLS suites count rows in."""
    db_name = f"aeos_create_{uuid.uuid4().hex[:12]}"
    with psycopg.connect(DATABASE_URL, autocommit=True) as conn:
        conn.execute(f'CREATE DATABASE "{db_name}"')
    target_url = _swap_database(DATABASE_URL, db_name)
    try:
        with psycopg.connect(target_url, autocommit=True) as conn:
            conn.execute(SHIM_SQL.read_text())
            for migration in MIGRATIONS:
                conn.execute((MIGRATIONS_DIR / migration).read_text())
            conn.execute(SEED_SQL)
        yield target_url
    finally:
        with psycopg.connect(DATABASE_URL, autocommit=True) as conn:
            conn.execute(
                "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                "WHERE datname = %s AND pid <> pg_backend_pid()",
                (db_name,),
            )
            conn.execute(f'DROP DATABASE IF EXISTS "{db_name}"')


@pytest.fixture
def real_client(fresh_database):
    """The API's view of the database: service_role, one commit per call."""
    with psycopg.connect(fresh_database, autocommit=True, row_factory=dict_row) as conn:
        conn.execute("SET ROLE service_role")
        yield RealDbClient(conn)


