@pytest.mark.parametrize("table", CREATE_CALLS)
def test_create_endpoint_persists_with_a_database_generated_id(real_client, admin_db, table):
    created = CREATE_CALLS[table](real_client)

    generated = uuid.UUID(created.id)
    assert generated.version == 4
    # Not an id the application supplied: the adapter dropped those.
    assert created.id not in real_client.discarded_ids.get(table, [])

    stored = admin_db.execute(
        sql.SQL(
            "SELECT organization_id::text, created_by::text FROM public.{} WHERE id = %s"
        ).format(sql.Identifier(table)),
        (created.id,),
    ).fetchone()
    assert stored == (ORG_A, USER_A)
