-- 009: server-generated primary keys.
--
-- Introduced by PR #55 as 005_primary_key_defaults.sql and renumbered to 009
-- here because PR #51 had already used 005-008. The SQL is unchanged.
--
-- 001 and 003 declare every `id` as `UUID PRIMARY KEY` with no default. Before
-- PR #51 the API never supplied one, so against a real database every create
-- endpoint failed with
--   23502 null value in column "id" ... violates not-null constraint
-- (the unit-test fake assigned ids itself and hid the defect).
--
-- PR #51 now generates ids in `insert_tenant_scoped_row`
-- (app/services/tenant_scope.py). This default is the database-level
-- counterpart: any writer that omits `id` still gets one, so neither layer is
-- a single point of failure. tests/test_create_persists_real_db.py proves the
-- default on its own by discarding the application-supplied id.
--
-- The id is generated by the server, never accepted from the client: every
-- create request model sets `extra="forbid"` and none declares `id`.
--
-- gen_random_uuid() is built into PostgreSQL 13+, so no extension is required.
--
-- Forward-only. Changes defaults only; no rows, policies, grants or types change.
--
-- ROLLBACK (restores the exact pre-009 schema; creates that omit `id` fail again):
--   ALTER TABLE public.<table> ALTER COLUMN id DROP DEFAULT;   -- for each table below

ALTER TABLE public.organizations        ALTER COLUMN id SET DEFAULT gen_random_uuid();
ALTER TABLE public.schools              ALTER COLUMN id SET DEFAULT gen_random_uuid();
ALTER TABLE public.users                ALTER COLUMN id SET DEFAULT gen_random_uuid();
